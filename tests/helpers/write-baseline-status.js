const fs = require('fs');
const path = require('path');

// Define the output paths based on the 3C flow requirements
const artifactsDir = path.join(__dirname, '../artifacts/results');
const generatedDir = path.join(__dirname, '../../missions/_shared/generated');

const latestStatusJson = path.join(artifactsDir, 'latest-status.json');
const baselineStatusJson = path.join(generatedDir, 'baseline-status.json');
const baselineStatusHtml = path.join(generatedDir, 'baseline-status.html');

function generateHtml(statusData) {
  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>SPRK Baseline Status</title>
  <style>
    :root {
      --bg-color: #121212;
      --text-color: #e0e0e0;
      --pass-color: #4ade80;
      --fail-color: #f87171;
      --card-bg: #1e1e1e;
    }
    body {
      font-family: system-ui, -apple-system, sans-serif;
      background-color: var(--bg-color);
      color: var(--text-color);
      padding: 2rem;
      margin: 0;
    }
    .status-card {
      background-color: var(--card-bg);
      padding: 1.5rem;
      border-radius: 8px;
      box-shadow: 0 4px 6px rgba(0,0,0,0.3);
      max-width: 600px;
    }
    .status-PASS { color: var(--pass-color); font-weight: bold; }
    .status-FAIL { color: var(--fail-color); font-weight: bold; }
    h2 { margin-top: 0; }
    .details { margin-top: 1rem; font-size: 0.9rem; color: #aaa; }
  </style>
</head>
<body>
  <div class="status-card">
    <h2>Baseline Validation Status</h2>
    <p>Overall Result: <span class="status-${statusData.overall}">${statusData.overall}</span></p>
    <p>Tests Passed: ${statusData.passed} / ${statusData.total}</p>
    <p>Last Run: ${statusData.timestamp}</p>
    <div class="details">
      <p>Generated by Playwright Validation Harness</p>
    </div>
  </div>
</body>
</html>`;
}

function writeBaselineStatus(testResults) {
  // 1. Create target directories if they don't exist to prevent write errors
  fs.mkdirSync(artifactsDir, { recursive: true });
  fs.mkdirSync(generatedDir, { recursive: true });

  const timestamp = new Date().toISOString();
  const statusData = {
    overall: testResults.failed === 0 ? "PASS" : "FAIL",
    passed: testResults.passed,
    failed: testResults.failed,
    total: testResults.passed + testResults.failed,
    timestamp: timestamp
  };

  // 2. Write the raw test results artifact for the developer
  fs.writeFileSync(latestStatusJson, JSON.stringify(testResults, null, 2));

  // 3. Write the mission-readable shared JSON for app.js to fetch
  fs.writeFileSync(baselineStatusJson, JSON.stringify(statusData, null, 2));

  // 4. Write the human-readable HTML template
  const htmlContent = generateHtml(statusData);
  fs.writeFileSync(baselineStatusHtml, htmlContent);

  console.log('Baseline status files written to missions/_shared/generated/');
}

module.exports = { writeBaselineStatus };